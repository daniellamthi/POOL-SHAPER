import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const textureDirectory = resolve(projectRoot, "public/textures/mosaico");
const outputFile = resolve(projectRoot, "src/configurator/materials/mosaic-assets.generated.ts");
const supportedExtensions = new Set([".webp", ".jpg", ".jpeg", ".png"]);

const filenames = (await readdir(textureDirectory))
  .filter((filename) => supportedExtensions.has(extname(filename).toLowerCase()))
  .sort((left, right) => left.localeCompare(right, "en", { sensitivity: "base" }));

if (filenames.length === 0) {
  throw new Error(`No mosaic textures found in ${textureDirectory}`);
}

const assets = filenames.map((filename) => {
  const stem = filename.slice(0, -extname(filename).length);
  const id = `mosaic-${stem
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "")}`;
  const uuid = /^[0-9a-f]{8}(?:-[0-9a-f]{4}){3}-[0-9a-f]{12}$/i.test(stem);
  const name = uuid
    ? `Mosaic ${stem.slice(0, 8).toUpperCase()}`
    : stem
        .replace(/[-_]+/g, " ")
        .replace(/\s+/g, " ")
        .trim()
        .replace(/\b\w/g, (character) => character.toUpperCase());
  return { id, name, filename };
});

const records = assets
  .map(
    ({ id, name, filename }) =>
      `  {\n    id: ${JSON.stringify(id)},\n    name: ${JSON.stringify(name)},\n    filename: ${JSON.stringify(filename)},\n  },`,
  )
  .join("\n");
const output = `// Generated by scripts/generate-mosaic-manifest.mjs. Do not edit manually.\nexport const MOSAIC_ASSETS = [\n${records}\n] as const;\n`;

let current = "";
try {
  current = await readFile(outputFile, "utf8");
} catch {
  // The first run creates the generated catalog.
}

if (current !== output) await writeFile(outputFile, output);
