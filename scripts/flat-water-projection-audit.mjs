import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
import ts from 'typescript';
import * as THREE from 'three';
const source = readFileSync('src/components/pool/three/flatWaterProjection.ts','utf8');
const photoModeState = {active:false};
const context = {exports:{},queueMicrotask,performance,console:{debug(){}},require: name => name === 'three' ? THREE : {photoModeState}};
runInNewContext(ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText,context);
const {FlatWaterProjection,isPoolOpticalReceiver} = context.exports;
let checks=0;
const check=(value,message)=>{assert(value,message);checks++;};
const scene=new THREE.Scene(), basin=new THREE.Group(); basin.name='pool-basin';scene.add(basin);
const material = new THREE.MeshStandardMaterial(), geometry = new THREE.BoxGeometry();
const mesh=new THREE.Mesh(geometry,material);basin.add(mesh);
const originalCompile=material.onBeforeCompile, originalKey=material.customProgramCacheKey, originalRender=mesh.onBeforeRender;
let target=null;
const renderer={getRenderTarget:()=>target};
const camera=new THREE.PerspectiveCamera();camera.position.set(8,6,5);camera.updateMatrixWorld();
const projection=new FlatWaterProjection(scene,1.333);projection.retain();projection.sync(camera,true,0);
const program=()=>{const shader={uniforms:{},vertexShader:'#include <common>\n#include <project_vertex>'};material.onBeforeCompile(shader,renderer);return shader;};
let shader=program();
check(shader.vertexShader.match(/vec4 poolFlatWaterClip/g).length===1,'One optical patch, not duplicate GLSL');
let readyCameraCalls=0;
projection.beforeCameraRender=()=>{readyCameraCalls++;scene.overrideMaterial=new THREE.ShaderMaterial();scene.onBeforeRender(renderer,scene,camera);scene.overrideMaterial=null;};
camera.position.x+=.2;camera.updateMatrixWorld();
const draw=(cameraArg=camera)=>mesh.onBeforeRender(renderer,scene,cameraArg,geometry,material,null);
scene.onBeforeRender(renderer,scene,camera);draw();
check(readyCameraCalls===1,'Actual camera-ready capture does not recursively capture its override pass');
check(shader.uniforms.poolLensCameraPosition.value.x===camera.position.x,'Colour receives final camera moved after sync, not previous-frame position');
check(!shader.uniforms.poolLensActive.value,'Opaque canonical main pass remains unchanged');
target=new THREE.WebGLRenderTarget(1,1);const version=material.version;draw();
check(shader.uniforms.poolLensActive.value,'Actual nested transmission activates optical projection');
check(material.version===version,'Pass changes never dirty or recompile a material');
photoModeState.active=true;draw();check(!shader.uniforms.poolLensActive.value,'PhotoMode remains its own optical owner');photoModeState.active=false;
draw(new THREE.PerspectiveCamera());check(!shader.uniforms.poolLensActive.value,'Mirror/other camera cannot acquire optical projection');
scene.overrideMaterial=new THREE.MeshDepthMaterial();draw();check(!shader.uniforms.poolLensActive.value,'Depth override is not mistaken for transmission');scene.overrideMaterial=null;
const keyA=material.customProgramCacheKey();
function finishB(shader){shader.vertexShader+='\n// NEW FINISH B';}
material.onBeforeCompile=finishB;material.needsUpdate=true;projection.sync(camera,true,0);
check(material.customProgramCacheKey()!==keyA,'Default key rekeys after owner changes only onBeforeCompile');
check(program().vertexShader.includes('NEW FINISH B'),'New original finish shader is preserved');
const versionStable=material.version;projection.sync(camera,true,0);draw();
check(material.version===versionStable,'Stable sync and draw do not churn material versions');
const before=Array.from(geometry.attributes.position.array);projection.sync(camera,false,0);draw();
check(!shader.uniforms.poolLensActive.value,'Disabled water/Infinity guard is identity');
check(before.every((v,i)=>v===geometry.attributes.position.array[i]),'No geometry changes');
basin.remove(mesh);projection.sync(camera,true,0);
check(mesh.onBeforeRender===originalRender,'Detached mesh owner callback restored immediately');
check(material.onBeforeCompile===finishB&&material.customProgramCacheKey===originalKey,'Detached material hooks restored without stale strong ownership');
check(projection.meshes.size===0&&projection.materials.size===0,'Removed objects are pruned, not retained until unmount');
basin.add(mesh);projection.sync(camera,true,0);
projection.release();projection.retain();projection.sync(camera,true,0);await new Promise(queueMicrotask);
check(mesh.onBeforeRender!==originalRender,'StrictMode immediate replay retains the resource');
projection.release();await new Promise(queueMicrotask);
check(mesh.onBeforeRender===originalRender&&material.onBeforeCompile===finishB,'True unmount restores owner hooks');
const first=new FlatWaterProjection(scene,1.333),second=new FlatWaterProjection(scene,1.333);
basin.add(mesh);first.retain();first.sync(camera,true,0);first.release();
second.retain();second.sync(camera,true,0);await new Promise(queueMicrotask);
check(program().vertexShader.match(/vec4 poolFlatWaterClip/g).length===1,'Sequential remount/HMR cannot stack released-owner shader wrappers');
second.release();await new Promise(queueMicrotask);
for(const name of ['sun-shelf-loungers','pool-automatic-lighting','pool-access-stainlessSteelLadder-straight']){
 const group=new THREE.Group();group.name=name;group.add(mesh);check(isPoolOpticalReceiver(mesh),'Submerged attached accessory shares projection');group.remove(mesh);
}
const exterior=new THREE.Group();exterior.name='deck-loungers';exterior.add(mesh);
check(!isPoolOpticalReceiver(mesh),'No projection of exterior furniture/grass');
scene.add(exterior);const scopedMesh=new THREE.Mesh(geometry,material);basin.add(scopedMesh);
const shared=new FlatWaterProjection(scene,1.333);shared.retain();shared.sync(camera,true,0);
check(material.onBeforeCompile===finishB,'Cross-scope shared material stays canonical rather than leaking optical state');
shared.release();await new Promise(queueMicrotask);
check(readFileSync('node_modules/three/src/renderers/WebGLRenderer.js','utf8').includes('_currentMaterialId = - 1;'),'Installed renderer invalidates material binding for target changes');
geometry.dispose();material.dispose();target.dispose();
console.log(JSON.stringify({status:'PASS',checks,scope:'Real Three material hooks/pass ownership/cache rekey/pruning; no GPU or visual claim'}));
